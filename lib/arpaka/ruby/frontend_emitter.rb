# frozen_string_literal: true

require "digest"
require "erb"
require "json"

module Arpaka::Ruby
  class FrontendEmitter
    RuntimeBundle = Data.define(:templates)
    DETAILED_RUNTIME_BUNDLE = RuntimeBundle.new(
      %w[frontend detailed/ast detailed/builder lexer].freeze
    ).freeze
    STRUCTURED_RUNTIME_BUNDLE = RuntimeBundle.new(
      %w[frontend detailed/ast detailed/builder lexer structured].freeze
    ).freeze

    def emit(parser:, artifacts:, class_name:, grammar_filename:, ruby_source:,
      runtime_bundle: DETAILED_RUNTIME_BUNDLE, ast_type: :detailed)
      rules = JSON.parse(artifacts.fetch("rules.json"))
      runtime_options = artifacts.fetch("runtime", {})
      runtime = runtime_bundle.templates.map do |template_name|
        template = File.read(File.join(__dir__, "runtime", "#{template_name}.rb.erb"))
        ERB.new(template, trim_mode: "-").result_with_hash(rules: rules, runtime: runtime_options,
          ast_type: ast_type)
      end.join("\n")
      notices = [File.read(File.expand_path("../../../LICENSE.txt", __dir__))]
      %w[COPYING BSDL].each do |name|
        path = ruby_source ? File.join(ruby_source, name) : File.join(__dir__, name)
        notices << File.read(path)
      end
      source = "# frozen_string_literal: true\n" \
        "# Generated by Arpaka #{Lrama::Ruby::VERSION}. Do not edit.\n" \
        "# Ruby source profile: #{ruby_source ? artifacts.fetch('source_profile') : 'parse.y only'}\n" \
        "# parse.y SHA256: #{Digest::SHA256.file(grammar_filename).hexdigest}\n" \
        "#{notices.join("\n").lines.map { |line| "# #{line}" }.join}\n"
      source << wrap_class(class_name, parser, runtime)
      validate(source)
      source
    rescue SyntaxError => error
      raise ::Arpaka::Error, "Invalid generated frontend: #{error.message}"
    end

    private

    def validate(source)
      # Compile in an isolated box to validate syntax without executing actions.
      ::Ruby::Box.new.eval(source)
    end

    def wrap_class(class_name, parser, runtime)
      definition = "class #{class_name.constant}\n#{parser}\n#{runtime}\nend\n"
      class_name.namespaces.reverse_each do |namespace|
        body = definition.lines.map { |line| "  #{line}" }.join
        definition = "module #{namespace}\n#{body}end\n"
      end
      definition
    end
  end
end
